/** Un ícono como SVG: cada píxel es un cuadrado de la grilla de 12; `clase` le da el color (currentColor). */
export function pixel(nombre, clase = "") {
  const filas = ICONOS_PIXEL[nombre];
  let lleno = "";
  let tenue = "";
  filas.forEach((fila, y) => {
    for (let x = 0; x < fila.length; x++) {
      if (fila[x] === "#") lleno += `M${x} ${y}h1v1h-1z`;
      else if (fila[x] === "+") tenue += `M${x} ${y}h1v1h-1z`;
    }
  });
  return (
    `<svg class="px ${clase}" viewBox="0 0 12 12" aria-hidden="true" focusable="false" shape-rendering="crispEdges">` +
    `<path d="${lleno}"/>${tenue ? `<path d="${tenue}" opacity=".45"/>` : ""}</svg>`
  );
}

// El ojo de Vigía (frontend/components/marca/OjoPixel.tsx): 11 x 5 puntos, la pupila en cruz.
const OJO = ["...XXXXX...", ".XXX.A.XXX.", "XX..AAA..XX", ".XXX.A.XXX.", "...XXXXX..."];

/** El ojo de puntos de Vigía, para presentar a Vigía en la portada de Gobserva. */
export function ojoVigia(clase = "") {
  let puntos = "";
  OJO.forEach((fila, y) => {
    for (let x = 0; x < fila.length; x++) {
      if (fila[x] === ".") continue;
      const orden = Math.round(Math.hypot(x - 5, (y - 2) * 1.6));
      puntos += `<circle cx="${x + 0.5}" cy="${y + 0.5}" r=".42" class="${fila[x] === "A" ? "ojo-pupila" : "ojo-parpado"}" style="--i:${orden}"/>`;
    }
  });
  return `<svg class="ojo ${clase}" viewBox="0 0 11 5" aria-hidden="true" focusable="false">${puntos}</svg>`;
}
